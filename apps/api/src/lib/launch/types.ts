// Structured Market Ready blocker codes (the governing spec requires a
// "deterministic Market Ready evaluator returning structured blockers",
// not free-text). Each code is stable and machine-checkable — the UI maps
// a code to copy, never parses `message` for meaning.
export const MARKET_READY_BLOCKER_CODES = [
  "AGENCY_AGREEMENT_NOT_SIGNED",
  "TARGET_LAUNCH_DATE_MISSING",
  "MISSING_REQUIRED_CAMPAIGN_ITEMS",
  "CAMPAIGN_ITEMS_BLOCKED",
  "PENDING_VENDOR_APPROVALS",
  "BUDGET_EXCEEDED",
  "NO_PORTAL_DESTINATIONS_CONFIGURED",
] as const;
export type MarketReadyBlockerCode = (typeof MARKET_READY_BLOCKER_CODES)[number];

export interface MarketReadyBlocker {
  code: MarketReadyBlockerCode;
  message: string;
  // Present for blockers scoped to specific records (e.g. which campaign
  // items are missing/blocked) so the UI can deep-link, without the
  // client having to parse `message`.
  refs?: Array<{ recordType: string; recordId: string }>;
}

export interface MarketReadyResult {
  ready: boolean;
  blockers: MarketReadyBlocker[];
  evaluatedAt: Date;
}

// Campaign item types that MUST exist and be COMPLETE for Market Ready to
// pass, regardless of template — every sales method still needs at least a
// photo and listing copy before a property is genuinely ready for the
// market. Template-specific extra items (floor plan, signage, brochure,
// etc.) are generated by the template but are not part of this hard floor.
export const REQUIRED_CAMPAIGN_ITEM_TYPES: readonly string[] = ["PHOTOGRAPHY", "COPYWRITING"];

// Any campaign item costing at or above this threshold requires a formal
// VendorApproval record before Market Ready can pass (see marketReady.ts).
// A snapshot at item-creation time (campaignItems.costApprovalRequired),
// not re-evaluated retroactively if this constant ever changes.
export const LAUNCH_VENDOR_APPROVAL_THRESHOLD_CENTS = 50_000; // $500 AUD

export class LaunchError extends Error {
  reason: string;
  constructor(reason: string, message: string) {
    super(message);
    this.reason = reason;
  }
}
